/**
 * UserCampsiteDetailsViewModel:
 *
 * Holds the state and actions for [UserCampsiteDetailsScreen].
 *
 * Call [start] once with the listing id and optional search range passed through navigation.
 * All other properties are computed from the live Firestore-backed lists, so they update
 * automatically when the database changes.
 */

// Much of the following ViewModel was generated with help of Claude Opus 5.5, 2026-11-01 after
// "Once selected, the availability calendar should be highlighted green with those selected dates.
// Only lotteries that are within searchStart and searchEnd should be included. If no searchSTart and searchEnd exist,
// then it should simply display all lotteries. What I have so far for these functions are in the ViewModel
// file attached, but it isn't quite working."
class UserCampsiteDetailsViewModel : ListingViewModel() {

    private var listingId by mutableStateOf<String?>(null)

    /** Id of the lottery the entrant has selected on the screen, or null if none is selected. */
    var selectedLotteryId by mutableStateOf<String?>(null)
        private set // publicly readable but can only be accessed within UserCampsiteDetailsViewModel

    private var searchStart by mutableStateOf<Date?>(null)
    private var searchEnd by mutableStateOf<Date?>(null)

    private var profileId by mutableStateOf("")

    /**
     * Sets which campsite and search range this screen is showing. Safe to call repeatedly; it only
     * resets the selection if one of the arguments actually changed (e.g. not on screen rotation).
     *
     * @param listingId Firestore document id of the campsite to display.
     * @param searchStart first day of the entrant's search range, or null if they did not search by date.
     * @param searchEnd last day of the entrant's search range, or null if they did not search by date.
     * @param profileId current entrants id, hides lotteries already joined
     *
     * Above KDoc generated by Claude Opus 5.5, 2026/11/03
     */
    fun start(listingId: String, profileId: String, searchStart: Date?, searchEnd: Date?) {
        if (this.listingId == listingId &&
            this.profileId == profileId &&
            this.searchStart == searchStart &&
            this.searchEnd == searchEnd) return
        this.listingId = listingId
        this.profileId = profileId
        this.searchStart = searchStart
        this.searchEnd = searchEnd
        selectedLotteryId = null
    }

    /**
     * Marks a lottery as selected so its dates are shown on the calendar and it can be joined.
     *
     * @param id Firestore document id of the selected lottery.
     */
    fun selectLottery(id: String){
        selectedLotteryId = id
    }

    /** The campsite being viewed, or null when loading */
    val listing: Listing? get() = _listings.firstOrNull { it.id == listingId}

    /** One card per open lottery that has this campsite */
    val lotteryCards: List<LotteryCardInfo> get() {
        val id = listingId ?: return emptyList()
        val now = Date()
        return _lotteries
            .filter { id in it.campsiteIDs }
            .filter { now in it.start..it.end}
            .filter { overlapsSearch(it) }
            .filter { profileId !in it.waitlist}
            .map {it.toCardInfo()}
    }

    /** true if any of the lottery's stay days falls inside the search range or no search range */
    private fun overlapsSearch(lottery: Lottery): Boolean {
        val start = searchStart?.toDayOnly() ?: return true
        val end = searchEnd?.toDayOnly() ?: return true
        return lottery.dates.any { date ->
            val day = date.toDayOnly()
            !day.before(start) && !day.after(end)
        }
    }

    /** lottery that the user has picked or null */
    private val selectedLottery: Lottery? get() = _lotteries.firstOrNull { it.id == selectedLotteryId}

    val hasCapacity: Boolean
        get() {
            val lottery = selectedLottery ?: return false
            if (profileId in lottery.waitlist) {
                return false
            }
            val capacity = lottery.waitlistCapacity ?: return false
            return lottery.waitlist.size < capacity
        }

    /** selected lottery days (green) */
    val lotteryDays: Set<Date>
        get() = selectedLottery?.dates?.map { it.toDayOnly() }?.toSet().orEmpty()

    /** banner text */
    val searchRangeText: String
        get() {
            val start = searchStart ?: return "No date chosen: all lotteries"
            val end = searchEnd ?: return "No date chosen: all lotteries"
            return formatDateRange(listOf(start, end))
        }

    /** calendar opens on the month the search starts in */
    val initialMonth: YearMonth?
        get() = (searchStart ?: lotteryDays.minOrNull())?.let { date ->
            val cal = Calendar.getInstance()
            cal.time = date
            YearMonth.of(cal.get(Calendar.YEAR), cal.get(Calendar.MONTH) + 1)
        }

    /**
     * adds the user to the lottery's waitlist.
     * arrayUnion is an atomic update, so people joining at the same time can't overwrite each other.
     *
     * @param lotteryId Firestore document id of the lottery to join
     * @param profileId id of the entrant joining
     * @param onResult called with true if user added to waitlist, false otw
    */
    fun joinLottery(lotteryId: String, profileId: String, onResult: (Boolean) -> Unit) {
        lotteriesRef.document(lotteryId)
            .update("waitlist", FieldValue.arrayUnion(profileId))
            .addOnSuccessListener {
                selectedLotteryId = null
                onResult(true)
            }
            .addOnFailureListener {
                onResult(false)
            }
    }

    // Lottery -> what lottery card displays
    private fun Lottery.toCardInfo() = LotteryCardInfo(
        id = id,
        title = title,
        lotteryRange = formatDateRange(dates),
        waitlistCount = waitlist.size,
        waitlistCapacity = waitlistCapacity,
        imageUrl = firstPhotoOf(campsiteIDs)
    )

    private fun firstPhotoOf(campsiteIds: List<String>): String? =
        campsiteIds.firstNotNullOfOrNull { cid ->
            _listings.firstOrNull { it.id == cid }?.photoUrls?.firstOrNull()
        }

}

/**
 * Formats a list of dates as a range from the earliest to the latest, e.g. "May 1, 2027 - May 7, 2027".
 *
 * @param dates the dates to format; order does not matter.
 * @return the formatted range, a single date if all dates are the same day, or "No dates found" if empty.
 *
 * Above KDoc generated with Claude Opus 5.5, 2026/11/03
 */
internal fun formatDateRange(dates: List<Date>): String {
    val first = dates.minOrNull() ?: return "No dates found"
    val last = dates.max()
    val format = SimpleDateFormat("MMM d, yyyy", Locale.getDefault())
    return if (first == last) format.format(first)
        else "${format.format(first)} - ${format.format(last)}"
}

/**
 * Parses a date passed through a navigation route.
 *
 * @param text a date in "yyyy-MM-dd" format, e.g. "2027-05-01".
 * @return the parsed date, or null if [text] is null or not a valid date.
 *
 * Above KDoc generated with Claude Opus 5.5, 2026/11/03
 */
internal fun parseRouteDate(text: String?): Date? {
    if (text == null) return null
    val format = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())
    format.isLenient = false
    return runCatching { format.parse(text) }.getOrNull()
}

