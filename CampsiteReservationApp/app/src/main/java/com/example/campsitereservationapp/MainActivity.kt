class MainActivity : ComponentActivity() {

    // Asks the user to allow notifications (Android 13+). The result isn't needed:
    // LocalNotifier checks the permission each time it shows a notification.
    private val requestNotificationPermission =
        registerForActivityResult(ActivityResultContracts.RequestPermission()) { }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()

        // Phone notifications: set up the channel, ask permission, and start watching Firestore
        // Generated by Claude Opus 5.5, 2026/11/25
        // Q. I need to set up notifications with android studio. I need to detect notifications from a Notifications
        // document from firebase, and then send a local notification to the device when one of these notifications
        // are created. How can I do this? I have provided the Notifications schema, and our current MainActivity.

        LocalNotifier.createChannel(this)
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            requestNotificationPermission.launch(android.Manifest.permission.POST_NOTIFICATIONS)
        }
        NotificationWatcher.start(this, getDeviceId(this))

        setContent {
            CampsiteReservationTheme {
                CampsiteReservationApp()
                //MessageScreen(  "V1hnZFPqEJQ4B2xCdEHM","W8liJRiysiUFhsZHVpKs",{})
                //ui.Owner.CampsiteDetails.dateViewer()
            }
        }
    }
}