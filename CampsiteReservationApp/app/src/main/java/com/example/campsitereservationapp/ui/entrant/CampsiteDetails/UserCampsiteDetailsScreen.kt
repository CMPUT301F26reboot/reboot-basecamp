/**
 * Stateful Campsite Details screen. Starts [UserCampsiteDetailsViewModel] with the navigation
 * arguments and passes its state to [UserCampsiteDetailsContent].
 *
 * @param listingId Firestore document id of the campsite to show.
 * @param profileId current entrants device id, used when joining lottery
 * @param searchStart first day of the entrant's search range, or null if none.
 * @param searchEnd last day of the entrant's search range, or null if none.
 * @param onBack called when the back button is tapped.
 * @param viewModel the screen's ViewModel; can be replaced for testing.
 *
 * Above KDoc generated by Claude Opus 5.5, 2026/11/03
 */
@Composable
fun UserCampsiteDetailsScreen(
    listingId: String,
    profileId: String,
    searchStart: Date?,
    searchEnd: Date?,
    onBack: () -> Unit,
    viewModel: UserCampsiteDetailsViewModel = viewModel()
) {
    LaunchedEffect(listingId, searchStart, searchEnd) { viewModel.start(listingId, profileId = profileId, searchStart, searchEnd) }

    val snackbarHostState = remember { SnackbarHostState() }
    val scope = rememberCoroutineScope()

    val listing = viewModel.listing

    UserCampsiteDetailsContent(
        isLoading = listing == null,
        name = listing?.name.orEmpty(),
        address = listing?.address.orEmpty(),
        rating = listing?.rating ?: 0.0,
        reviewNum = listing?.numOfReviews ?: 0,
        maxOccupancy = listing?.maxOccupancy ?: 0,
        ownerName = listing?.ownerName.orEmpty(),
        description = listing?.description.orEmpty(),
        tags = listing?.tags.orEmpty(),
        photoUrls = listing?.photoUrls.orEmpty(),
        lotteryDays = viewModel.lotteryDays,
        desiredDaysRange = viewModel.searchRangeText,
        initialMonth = viewModel.initialMonth,
        lotteries = viewModel.lotteryCards,
        selectedLotteryId = viewModel.selectedLotteryId,
        hasCapacity = viewModel.hasCapacity,
        onSelectLottery = viewModel::selectLottery,
        onJoin = { lotteryId ->
            viewModel.joinLottery(
                lotteryId,
                profileId = profileId,
                onResult = {success ->
                    val message = if (success) {
                        "You joined the lottery!"
                    } else {
                        "Couldn't join the lottery. Please try again."
                    }

                    scope.launch {
                        snackbarHostState.showSnackbar(message)
                    }
                }
            )
        },
        onBack = onBack,
        snackbarHostState = snackbarHostState
    )
}

/**
 * Stateless Campsite Details UI: campsite summary, date banner, selectable lottery cards,
