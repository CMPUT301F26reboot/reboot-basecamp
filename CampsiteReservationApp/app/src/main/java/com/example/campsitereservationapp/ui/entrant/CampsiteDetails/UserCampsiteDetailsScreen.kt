/**
 * One selectable lottery card showing a photo, the title, the stay dates, and the waitlist size.
 * The whole card is tappable and announced as a radio button by screen readers.
 *
 * @param lottery the lottery to display.
 * @param selected whether this card is currently selected.
 * @param onSelect called when the card is tapped.
 *
 * Above KDoc generated by Claude Opus 5.5, 2026/11/03
 */

// Following function code for LotteryCard written by Claude Opus 5.5,
// "How can I display a lazy column of lotteries that are selectable? If no lotteries are available
//  it should say there are no lotteries to display", 2026-11-01
@Composable
private fun LotteryCard(
    lottery: LotteryCardInfo,
    selected: Boolean,
    onSelect: () -> Unit
){
    OutlinedCard(
        border = BorderStroke(
            width = if (selected) 2.dp else 1.dp,
            color = if (selected) MaterialTheme.colorScheme.onSurface
                    else MaterialTheme.colorScheme.outlineVariant
        ),
        modifier = Modifier
            .fillMaxWidth()
            .clip(MaterialTheme.shapes.medium)
            .selectable(selected = selected, onClick = onSelect, role = Role.RadioButton)
    ){
        Column(modifier = Modifier.padding(12.dp)) {
            Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                AsyncImage(
                    model = lottery.imageUrl?.let { decodeBase64Image(it) },
                    placeholder = painterResource(R.drawable.sample_campsite),
                    error = painterResource(R.drawable.sample_campsite),
                    contentDescription = null,
                    contentScale = ContentScale.Crop,
                    modifier = Modifier
                        .size(100.dp)
                        .clip(MaterialTheme.shapes.medium)
                )
                Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {

                    Text(
                        text = lottery.title,
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold
                    )

                    IconText(Icons.Default.DateRange, lottery.lotteryRange)

                    Text(
                        text = lottery.waitlistCapacity
                            ?.let { "Current Waitlist: ${lottery.waitlistCount}/$it"}
                            ?: "Current Waitlist: ${lottery.waitlistCount}",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }
            Spacer(Modifier.height(8.dp))
            Row(verticalAlignment = Alignment.CenterVertically){
                Text(
                    text = if (selected) "Selected" else "Select",
                    style = MaterialTheme.typography.bodyMedium,
                    fontWeight = FontWeight.Bold,
                    modifier = Modifier.weight(1f)
                )
                RadioButton(selected = selected, onClick = null)
            }
        }
    }

}

