 * @param selectedLotteryId id of the selected lottery, or null if none.
 * @param onSelectLottery called with a lottery's id when its card is tapped.
 * @param onJoin called with the selected lottery's id when Join lottery is tapped.
 * @param onBack called when the back button is tapped.
 *
 * Above KDOC generated by Claude Opus 5.5, 2026/11/03
 */
@Composable
internal fun UserCampsiteDetailsContent(
    isLoading: Boolean,
    name: String,
    address: String,
    rating: Double,
    reviewNum: Int,
    maxOccupancy: Int,
    ownerName: String,
    description: String,
    tags: List<String>,
    photoUrls: List<String>,
    lotteryDays: Set<Date>,
    desiredDaysRange: String,
    initialMonth: YearMonth?,
    lotteries: List<LotteryCardInfo>,
    selectedLotteryId: String?,
    hasCapacity: Boolean,
    onSelectLottery: (String) -> Unit,
    onJoin: (String) -> Unit,
    onBack: () -> Unit,
    snackbarHostState: SnackbarHostState = remember { SnackbarHostState() }
) {

    Scaffold(
        snackbarHost = { SnackbarHost(snackbarHostState) },
        bottomBar = {
            Surface(tonalElevation = 3.dp) {
                Button(
                    onClick = {
                        if (selectedLotteryId != null) {
                            onJoin(selectedLotteryId)
                        }
                    },
                    enabled = selectedLotteryId != null && hasCapacity,
                    shape = MaterialTheme.shapes.large,
                    colors = ButtonDefaults.buttonColors(
                        containerColor = MaterialTheme.colorScheme.onSurface,
                        contentColor = MaterialTheme.colorScheme.surface
                    ),
                    contentPadding = PaddingValues(vertical = 16.dp),
                    modifier = Modifier
                        .fillMaxWidth()
                        .navigationBarsPadding()
                        .padding(16.dp)
                ) {
                    Text("Join lottery", fontWeight = FontWeight.Bold)
                }
            }
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
        ) {
            FilledTonalIconButton(
                onClick = onBack,
                modifier = Modifier.padding(start = 16.dp, top = 8.dp)
            ) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
            }

            if (isLoading) {
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxWidth(),
                    contentAlignment = Alignment.Center
                ) {
                    CircularProgressIndicator()
                }
            } else {
                Column(
                    modifier = Modifier
                        .weight(1f)
                        .verticalScroll(rememberScrollState())
                        .padding(horizontal = 16.dp, vertical = 8.dp),
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    Text(
                        text = name,
                        style = MaterialTheme.typography.headlineMedium,
                        fontWeight = FontWeight.Bold
                    )
                    Text(
                        text = address,
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )

                    Row {
                        IconText(Icons.Filled.Star, "$rating ($reviewNum reviews)", tint = RatingAmber)
                    }

                    InfoRow(label = "Maximum Occupancy", value = "$maxOccupancy guests")
                    InfoRow(label = "Owner", value = ownerName)

                    SectionTitle("Description")
                    Text(
                        text = description,
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )

                    if (tags.isNotEmpty()) {
                        SectionTitle("Tags")
                        FlowRow(
                            horizontalArrangement = Arrangement.spacedBy(8.dp),
                            verticalArrangement = Arrangement.spacedBy(8.dp)
                        ) {
                            tags.forEach { TagChip(it) }
                        }
                    }

                    Surface(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(vertical = 18.dp),
                        shape = MaterialTheme.shapes.medium,
                        color = MaterialTheme.colorScheme.surfaceVariant
                    ) {
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            verticalAlignment = Alignment.CenterVertically
                        ){
                            Icon(
                                imageVector = Icons.Filled.DateRange,
                                contentDescription = "Date Range",
                                tint = MaterialTheme.colorScheme.onSurfaceVariant,
                                modifier = Modifier
                                    .size(38.dp)
                                    .padding(horizontal = 2.dp)
                            )

                            Column() {
                                Text(
                                    text = "Lotteries within: ",
                                    style = MaterialTheme.typography.labelLarge,
                                    fontWeight = FontWeight.Bold,
                                    modifier = Modifier.padding(horizontal = 4.dp, vertical = 2.dp)
                                )

                                Text(
                                    text = desiredDaysRange,
                                    style = MaterialTheme.typography.titleMedium,
                                    fontWeight = FontWeight.W900,
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                                )
                            }
                        }
                    }

                    // Following code related to LotteryCard written by Claude Opus 5.5,
                    // "How can I display a lazy column of lotteries that are selectable? If no lotteries are available
                    //  it should say there are no lotteries to display", 2026-11-01

                    Row(verticalAlignment  = Alignment.CenterVertically) {
                        Text(
                            text = "Lotteries with this campsite",
                            style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.Bold,
                            modifier = Modifier.weight(1f)
                        )
                        Text(
                            text = "${lotteries.size} lotteries",
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }

                    if (lotteries.isEmpty()) {
                        Text(
                            text = "No lotteries are available for this campsite right now.",
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    } else {
                        Column(
                            modifier = Modifier.selectableGroup(),
                            verticalArrangement = Arrangement.spacedBy(12.dp)
                        ) {
                            lotteries.forEach { lottery ->
                                key(lottery.id) {
                                    LotteryCard(
                                        lottery = lottery,
                                        selected = lottery.id == selectedLotteryId,
                                        onSelect = { onSelectLottery(lottery.id) }
                                    )
                                }
                            }
                        }
                    }
                    //shows campsite photos
                    if (photoUrls.isNotEmpty()) {
                        LazyRow(
                            horizontalArrangement = Arrangement.spacedBy(12.dp),
                            modifier = Modifier.padding(vertical = 6.dp)
                        ) {
                            items(photoUrls) { url ->
                                AsyncImage(
                                    model = decodeBase64Image(url),
                                    placeholder = painterResource(R.drawable.sample_campsite),
                                    error = painterResource(R.drawable.sample_campsite),
                                    contentDescription = "Photo of $name",
                                    contentScale = ContentScale.Crop,
                                    modifier = Modifier
                                        .size(100.dp)
                                        .clip(MaterialTheme.shapes.large)
                                )
                            }
                        }
                    }

                    AvailabilityCalendar(
                        availableDays = lotteryDays,
                        selectedDays = emptySet(),
                        onDayClick = { },
                        title = "Available spots",
                        initialMonth = initialMonth
                    )

                    Spacer(Modifier.height(8.dp))
                }
            }
        }
    }
}

